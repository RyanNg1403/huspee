export type AssistantMessageKey = keyof (typeof messages)['vi'];

const ORDER_STATUSES = [
  'UNPAID',
  'READY_TO_SHIP',
  'PROCESSED',
  'SHIPPED',
  'TO_CONFIRM_RECEIVE',
  'COMPLETED',
  'IN_CANCEL',
  'CANCELLED',
  'TO_RETURN',
] as const;

/** Message key for an order status code, or undefined for a status this UI does not know. */
export function orderStatusKey(status: string): AssistantMessageKey | undefined {
  return (ORDER_STATUSES as readonly string[]).includes(status)
    ? (`orderStatus_${status}` as AssistantMessageKey)
    : undefined;
}
